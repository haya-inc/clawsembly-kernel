import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  mkdtemp,
  mkdir,
  readFile,
  readdir,
  rm,
  writeFile
} from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lockPath = path.join(root, "contracts", "openclaw-artifact.json");
const contractPath = path.join(root, "contracts", "openclaw-sqlite-contract.generated.json");
const schemaModulePath = path.join(root, "src", "generated", "openclaw-state-schema.ts");
const check = process.argv.includes("--check");

const requirementSpecs = [
  { id: "node-sqlite-module", patterns: [/node:sqlite/u] },
  { id: "database-sync", patterns: [/\bDatabaseSync\b/u] },
  { id: "statement-get", patterns: [/\.get\(/u] },
  { id: "statement-all", patterns: [/\.all\(/u] },
  { id: "statement-run", patterns: [/\.run\(/u] },
  { id: "statement-iterate", patterns: [/\.iterate\(/u] },
  { id: "statement-columns", patterns: [/\.columns\(\)/u] },
  { id: "read-only-open", patterns: [/readOnly:\s*true/u] },
  { id: "extension-loading", patterns: [/\.enableLoadExtension\(/u, /\.loadExtension\(/u] },
  { id: "begin-immediate", patterns: [/BEGIN IMMEDIATE/u] },
  { id: "nested-savepoint", patterns: [/SAVEPOINT \$\{savepointName\}/u, /ROLLBACK TO SAVEPOINT/u] },
  { id: "wal-journal", patterns: [/PRAGMA journal_mode = WAL/u] },
  { id: "wal-checkpoint", patterns: [/PRAGMA wal_checkpoint\(/u] },
  { id: "busy-timeout", patterns: [/PRAGMA busy_timeout/u] },
  { id: "normal-synchronous", patterns: [/PRAGMA synchronous = \$\{synchronous\}/u] },
  { id: "foreign-keys", patterns: [/PRAGMA foreign_keys = ON/u] },
  { id: "attach-database", patterns: [/ATTACH DATABASE/u] },
  { id: "vacuum-into", patterns: [/VACUUM INTO/u] },
  { id: "sqlite-version-safety", patterns: [/SQLite 3\.51\.3\+/u] }
];

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

async function walk(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(target));
    else files.push(target);
  }
  return files;
}

function extractArchive(archivePath, directory) {
  const result = spawnSync("tar", [
    "-xzf",
    archivePath,
    "-C",
    directory,
    "package/dist"
  ], {
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024
  });
  if (result.status !== 0) {
    throw new Error(`tar extraction failed: ${result.stderr || result.stdout}`);
  }
}

function generatedSchemaModule(artifact, schema, schemaInfo) {
  if (schema.includes("`") || schema.includes("${")) {
    throw new Error("OpenClaw state schema cannot be emitted as a literal safely");
  }
  return `// Generated by scripts/generate-openclaw-sqlite-contract.mjs.
// Source: ${artifact.name}@${artifact.version} (${schemaInfo.sourceFile})
// Schema SHA-256: ${schemaInfo.sha256}

export const OPENCLAW_ARTIFACT = Object.freeze(${JSON.stringify({
    name: artifact.name,
    version: artifact.version,
    integrity: artifact.integrity,
    nodeEngine: artifact.nodeEngine
  }, null, 2)} as const);

export const OPENCLAW_STATE_SCHEMA_SHA256 = "${schemaInfo.sha256}";

export const OPENCLAW_STATE_SCHEMA_SQL = \`${schema}\`;
`;
}

async function assertOrWrite(target, expected) {
  if (check) {
    let actual;
    try {
      actual = await readFile(target, "utf8");
    } catch {
      throw new Error(`${path.relative(root, target)} is missing; run npm run contract:generate`);
    }
    if (actual !== expected) {
      throw new Error(`${path.relative(root, target)} is stale; run npm run contract:generate`);
    }
    return;
  }
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, expected);
}

async function main() {
  const artifact = JSON.parse(await readFile(lockPath, "utf8"));
  const temporaryDirectory = await mkdtemp(path.join(tmpdir(), "clawsembly-openclaw-contract-"));
  try {
    const response = await fetch(artifact.tarball);
    if (!response.ok) {
      throw new Error(`artifact download failed with HTTP ${response.status}`);
    }
    const archive = Buffer.from(await response.arrayBuffer());
    const integrity = `sha512-${createHash("sha512").update(archive).digest("base64")}`;
    if (integrity !== artifact.integrity) {
      throw new Error(`artifact integrity mismatch: expected ${artifact.integrity}, got ${integrity}`);
    }

    const archivePath = path.join(temporaryDirectory, "openclaw.tgz");
    const extractionPath = path.join(temporaryDirectory, "unpacked");
    await writeFile(archivePath, archive);
    await mkdir(extractionPath);
    extractArchive(archivePath, extractionPath);

    const distRoot = path.join(extractionPath, "package", "dist");
    const sourceFiles = (await walk(distRoot))
      .filter((file) => file.endsWith(".js"))
      .sort();
    const sources = new Map();
    for (const file of sourceFiles) {
      sources.set(
        path.relative(path.join(extractionPath, "package"), file),
        await readFile(file, "utf8")
      );
    }

    const schemaEntries = [...sources].filter(([, source]) => (
      source.includes("const OPENCLAW_STATE_SCHEMA_SQL = `")
    ));
    if (schemaEntries.length !== 1) {
      throw new Error(`expected one generated OpenClaw state schema, found ${schemaEntries.length}`);
    }
    const [schemaSourceFile, schemaSource] = schemaEntries[0];
    const schemaMatch = schemaSource.match(
      /const OPENCLAW_STATE_SCHEMA_SQL = `([\s\S]*?)`;/u
    );
    if (!schemaMatch) throw new Error("OpenClaw state schema literal was not extractable");
    const schema = schemaMatch[1];

    const requirements = requirementSpecs.map(({ id, patterns }) => {
      const evidence = [...sources]
        .filter(([file, source]) => (
          /sqlite/iu.test(file)
          || /node:sqlite|\bDatabaseSync\b|ATTACH DATABASE|VACUUM INTO/u.test(source)
        ))
        .filter(([, source]) => patterns.every((pattern) => pattern.test(source)))
        .map(([file, source]) => ({ file, sha256: sha256(source) }))
        .slice(0, 5);
      if (evidence.length === 0) {
        throw new Error(`required SQLite behavior "${id}" was not found in the artifact`);
      }
      return { id, evidence };
    });

    const schemaInfo = {
      sourceFile: schemaSourceFile,
      sourceFileSha256: sha256(schemaSource),
      sha256: sha256(schema),
      bytes: Buffer.byteLength(schema),
      lines: schema.split("\n").length,
      tables: (schema.match(/CREATE TABLE/gu) ?? []).length,
      indexes: (schema.match(/CREATE (?:UNIQUE )?INDEX/gu) ?? []).length
    };
    const contract = {
      schemaVersion: 1,
      artifact,
      stateSchema: schemaInfo,
      requirements
    };

    await assertOrWrite(
      contractPath,
      `${JSON.stringify(contract, null, 2)}\n`
    );
    await assertOrWrite(
      schemaModulePath,
      generatedSchemaModule(artifact, schema, schemaInfo)
    );
    process.stdout.write(
      `${check ? "Verified" : "Generated"} OpenClaw SQLite contract for ${artifact.name}@${artifact.version}: `
      + `${schemaInfo.tables} tables, ${schemaInfo.indexes} indexes, ${requirements.length} required behaviors.\n`
    );
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
}

await main();
